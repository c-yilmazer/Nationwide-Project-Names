# Step 1: Ask for state
def Sales_input():
    """Interactive Salesforce project lookup by state and project."""
    
    # Step 1: Ask for state
    State = input("Enter the abbreviation of the state: ").strip().upper()

    if State not in states:
        print("❌ State not found in database.")
        return  # exits function safely

    # Step 2: List all projects with numbers + stage + agent
    print(f"\nHere are the projects in {State}:\n")

    projects = list(states[State].keys())
    for i, project in enumerate(projects, start=1):
        stage = states[State][project]['Stage']
        agent = states[State][project]['Agent']
        print(f"{i}. {project} ({stage} || {agent})")

    # Step 3: User selects by number
    try:
        project_number = int(input("\nEnter the number of the project you want to open: "))
        if project_number < 1 or project_number > len(projects):
            print("❌ Invalid project number.")
            return
    except ValueError:
        print("❌ Please enter a valid number.")
        return

    # Step 4: Open Salesforce link
    selected_project = projects[project_number - 1]
    project_data = states[State][selected_project]
    salesforce_id = project_data['SalesForce ID']

    if salesforce_id.strip() == "":
        print("⚠️ No Salesforce ID available for this project.")
    else:
        url = f"https://ps-crm-dupont.lightning.force.com/lightning/r/Opportunity/{salesforce_id}/view"
        print(f"\n🔗 Opening Salesforce page for: {selected_project} ({project_data['Stage']} || {project_data['Agent']})")
        webbrowser.open_new_tab(url)